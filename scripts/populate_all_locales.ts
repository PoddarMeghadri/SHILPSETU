// Function to inject keys into a file
function addKeysToFile(filePath: string, dictVarName: string, langCode: string) {
  let content = fs.readFileSync(filePath, 'utf-8');
  
  // Find where dictVarName is defined
  const regex = new RegExp(`export const ${dictVarName}(: Record<string, string>)? = {([\\s\\S]*?)};`);
  const match = content.match(regex);
  if (!match) {
    console.error(`Could not find ${dictVarName} in ${filePath}`);
    return;
  }

  const existingBlock = match[2];
  const linesToAdd: string[] = [];

  for (const [key, langMap] of Object.entries(translationsToAdd)) {
    // Check if key is already in existingBlock
    const keyRegex = new RegExp(`\\b${key}:`);
    if (!keyRegex.test(existingBlock)) {
      const val = langMap[langCode] || langMap['hi'] || langMap['en'] || key;
      // escape single quotes
      const escapedVal = val.replace(/'/g, "\\'");
      linesToAdd.push(`  ${key}: '${escapedVal}',`);
    }
  }

  if (linesToAdd.length > 0) {
    const updatedBlock = existingBlock.trimEnd() + '\n' + linesToAdd.join('\n') + '\n';
    const replacement = `export const ${dictVarName}$1 = {${updatedBlock}};`;
    content = content.replace(regex, replacement);
    fs.writeFileSync(filePath, content, 'utf-8');
    console.log(`Added ${linesToAdd.length} keys to ${dictVarName} (${langCode}) in ${path.basename(filePath)}`);
  } else {
    console.log(`No keys needed for ${dictVarName} (${langCode})`);
  }
}

