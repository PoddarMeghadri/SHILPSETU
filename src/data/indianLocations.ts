export function parseLocationString(locationStr: string): { state: string; city: string } {
  if (!locationStr) return { state: 'Uttar Pradesh', city: 'Varanasi' };
  
  const parts = locationStr.split(',').map((p) => p.trim());
  if (parts.length >= 2) {
    const cityCandidate = parts[0];
    const stateCandidate = parts[1];
    
    // Look up matching state
    const matchedState = INDIAN_STATES_AND_CITIES.find(
      (s) => s.state.toLowerCase() === stateCandidate.toLowerCase()
    );
    
    if (matchedState) {
      const matchedCity = matchedState.cities.find(
        (c) => c.toLowerCase() === cityCandidate.toLowerCase()
      );
      return {
        state: matchedState.state,
        city: matchedCity || matchedState.cities[0] || cityCandidate,
      };
    }
  }

  // Fallback search in all states
  for (const s of INDIAN_STATES_AND_CITIES) {
    for (const c of s.cities) {
      if (locationStr.toLowerCase().includes(c.toLowerCase())) {
        return { state: s.state, city: c };
      }
    }
  }

  return { state: 'Uttar Pradesh', city: 'Varanasi' };
}
